def generate_all_transformations_vectorized(tensor_batch: np.ndarray) -> List[cp.ndarray]:
    """
    Generate all 8 transformations for a batch of 2D tensors efficiently.

    Args:
        tensor_batch: Shape (batch_size, height, width)

    Returns:
        List of 8 arrays, each with shape (batch_size, height, width) or (batch_size, width, height)
    """
    transformations = []

    # Original and 3 rotations
    current = tensor_batch
    for i in range(4):
        transformations.append(current.copy())
        current = np.rot90(current, axes=(-2, -1))

    # Horizontal flip and its 3 rotations
    flipped = np.flip(tensor_batch, axis=-1)  # flip along width
    current = flipped
    for i in range(4):
        transformations.append(current.copy())
        current = np.rot90(current, axes=(-2, -1))

    return transformations

def get_canonical_forms_vectorized(tensor_batch: np.ndarray, rotation_invariant: bool = False) -> List[Tuple[int, ...]]:
    """
    Get canonical forms for a batch of tensors efficiently.

    Args:
        tensor_batch: Shape (batch_size, height, width)
        rotation_invariant: If True, apply rotation and reflection invariance

    Returns:
        List of canonical form tuples
    """
    batch_size = tensor_batch.shape[0]
    canonical_forms = []

    if rotation_invariant:
        # Generate all transformations
        all_transforms = generate_all_transformations_vectorized(tensor_batch)

        for batch_idx in range(batch_size):
            # Get canonical form for each of the 8 transformations
            batch_canonicals = []

            for transform in all_transforms:
                tensor = transform[batch_idx]
                flat = tensor.flatten()

                # Fast relabeling using unique
                unique_vals, inverse_indices = unique_with_inverse_indices(flat)
                canonical_tuple = tuple(inverse_indices)
                batch_canonicals.append(canonical_tuple)

            # Get lexicographically smallest canonical form
            min_canonical = min(batch_canonicals)
            canonical_forms.append(min_canonical)
    else:
        # Simple relabeling only - much faster
        for batch_idx in range(batch_size):
            tensor = tensor_batch[batch_idx]
            rev_tensor = np.flip(tensor, axis=-1)
            flat = tensor.flatten()
            rev_flat = rev_tensor.flatten()

            # Fast relabeling using unique
            unique_vals, inverse_indices = unique_with_inverse_indices(flat)
            canonical_tuple = tuple(inverse_indices)
            canonical_forms.append(canonical_tuple)

            unique_vals, inverse_indices = unique_with_inverse_indices(rev_flat)
            canonical_tuple = tuple(inverse_indices)
            canonical_forms.append(canonical_tuple)

    return canonical_forms

def unique_tensors_no_relabeling_fast(tensor_batch: np.ndarray, rotation_invariant: bool = False, chunk_size=1000) -> np.ndarray:
    """
    Fast vectorized version to find unique tensors considering relabeling equivalence,
    and optionally rotations/reflections.

    Args:
        tensor_batch: Batch of tensors with shape (batch_size, height, width)
        rotation_invariant: If True, also consider rotations and reflections as equivalent

    Returns:
        Array of unique tensors (subset of input batch)
    """
    if len(tensor_batch) == 0:
        return tensor_batch

    # Handle large batches in chunks to manage memory
    if len(tensor_batch) > chunk_size:
        return process_in_chunks(tensor_batch, chunk_size, rotation_invariant)

    # Get canonical forms for all tensors
    canonical_forms = get_canonical_forms_vectorized(tensor_batch, rotation_invariant)

    # Find unique canonical forms
    seen_forms = set()
    unique_indices = []

    for i, canonical in enumerate(canonical_forms):
        canonical = tuple(v.item() for v in canonical)
        if canonical not in seen_forms:
            seen_forms.add(canonical)
            unique_indices.append(i)

    return tensor_batch[unique_indices]

def process_in_chunks(tensor_batch: np.ndarray, chunk_size: int, rotation_invariant: bool = False) -> np.ndarray:
    """Process large batches in chunks to manage memory usage."""
    unique_tensors = []
    seen_forms = set()

    for i in range(0, len(tensor_batch), chunk_size):
        end_idx = min(i + chunk_size, len(tensor_batch))
        chunk = tensor_batch[i:end_idx]

        canonical_forms = get_canonical_forms_vectorized(chunk, rotation_invariant)

        for j, canonical in enumerate(canonical_forms):
            if canonical not in seen_forms:
                seen_forms.add(canonical)
                unique_tensors.append(chunk[j])

    return np.array(unique_tensors) if unique_tensors else np.empty_like(tensor_batch[:0])

# Ultra-fast version using hash-based approach
def unique_tensors_no_relabeling_ultra_fast(tensor_batch: np.ndarray, rotation_invariant: bool = False, relabel=False) -> np.ndarray:
    """
    Ultra-fast version using optimized processing and minimal Python loops.

    Args:
        tensor_batch: Batch of tensors with shape (batch_size, height, width)
        rotation_invariant: If True, also consider rotations and reflections as equivalent

    Returns:
        Array of unique tensors (subset of input batch)
    """
    if len(tensor_batch) == 0:
        return tensor_batch

    batch_size = tensor_batch.shape[0]
    unique_indices = []
    seen_hashes = set()

    if rotation_invariant:
        # Generate all transformations
        all_transforms = generate_all_transformations_vectorized(tensor_batch)

        for batch_idx in tqdm(list(range(batch_size))):
            # Get all 8 canonical forms for this tensor
            canonicals = []

            for transform in all_transforms:
                tensor = transform[batch_idx]
                flat = tensor.flatten()

                # Fast unique + inverse for relabeling
                if relabel:
                    _, inverse = unique_with_inverse_indices(flat)
                    canonical = tuple(v.item() for v in inverse)
                else:
                    canonical = tuple(v.item() for v in flat)
                canonicals.append(canonical)

            # Get minimum canonical form
            min_canonical = min(canonicals)

            # Use hash for faster lookup
            canonical_hash = hash(min_canonical)
            if canonical_hash not in seen_hashes:
                seen_hashes.add(canonical_hash)
                unique_indices.append(batch_idx)
    else:
        # Simple relabeling only - much faster
        for batch_idx in tqdm(list(range(batch_size))):
            tensor = tensor_batch[batch_idx]
            flat = tensor.flatten()

            # Fast unique + inverse for relabeling
            if relabel:
                _, inverse = unique_with_inverse_indices(flat)
                canonical = tuple(v.item() for v in inverse)
            else:
                canonical = tuple(v.item() for v in flat)

            # Use hash for faster lookup
            canonical_hash = hash(canonical)
            if canonical_hash not in seen_hashes:
                seen_hashes.add(canonical_hash)
                unique_indices.append(batch_idx)

    return tensor_batch[unique_indices]

