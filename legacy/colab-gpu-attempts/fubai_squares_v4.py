def unique_with_inverse_indices(arr):
    """
    Returns unique elements in order of first appearance and the inverse indices.

    Parameters:
    arr (np.ndarray): Input 1D array of integers.

    Returns:
    tuple: (unique_values, inverse_indices)
    """
    unique_vals, first_indices, inverse = np.unique(arr, return_index=True, return_inverse=True)
    sorted_order = np.argsort(first_indices)
    unique_in_order = unique_vals[sorted_order]

    # Create mapping from original unique -> ordered unique index
    reorder_map = np.empty_like(sorted_order)
    reorder_map[sorted_order] = np.arange(len(sorted_order))

    reordered_inverse = reorder_map[inverse]

    return unique_in_order, reordered_inverse

