def generate_all_sequences_meshgrid(row_size, vocab_size):
    """
    Alternative implementation using np.meshgrid for generating all sequences.
    More memory efficient for smaller vocab_size and row_size.
    """
    if row_size <= 0 or vocab_size <= 0:
        raise ValueError("row_size and vocab_size must be positive integers")

    # Create arrays for each position
    arrays = [np.arange(vocab_size) for _ in range(row_size)]

    # Generate meshgrid
    grids = np.meshgrid(*arrays, indexing='ij')

    # Stack and reshape to get all sequences
    sequences = np.stack(grids, axis=-1).reshape(-1, row_size)

    return sequences

