def rotate_batch_2d(batch):
    """
    Generate all 4 rotation orientations (0°, 90°, 180°, 270°) for a batch of 2D tensors.

    Args:
        batch: numpy array of shape (N, H, W) where N is batch size, H is height, W is width

    Returns:
        numpy array of shape (4*N, H, W) containing all rotations
        Order: [original, 90°, 180°, 270°] for each input tensor
    """
    if batch.ndim != 3:
        raise ValueError(f"Expected 3D input (batch_size, height, width), got {batch.ndim}D")

    batch_size, height, width = batch.shape

    # Generate all 4 rotations
    rot_0 = batch                                    # 0° (original)
    rot_90 = cp.rot90(batch, k=1, axes=(1, 2))      # 90° counterclockwise
    rot_180 = cp.rot90(batch, k=2, axes=(1, 2))     # 180°
    rot_270 = cp.rot90(batch, k=3, axes=(1, 2))     # 270° counterclockwise (90° clockwise)

    # Stack all rotations: for each original tensor, include all 4 rotations
    rotated_batch = cp.stack([rot_0, rot_90, rot_180, rot_270], axis=1)

    # Reshape to (4*N, H, W) - note that H and W might swap for 90°/270° rotations
    return rotated_batch.reshape(-1, *rotated_batch.shape[2:])

