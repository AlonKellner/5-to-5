def generate_partitions(row_size, vocab_size):
    """
    Generate all possible unique partitions of a sequence of length `row_size`
    into a maximum of `vocab_size` partitions using partition indices.

    Each position in the sequence gets assigned a partition ID from 0 to vocab_size-1.
    Only returns partitions that use consecutive partition IDs starting from 0.

    Args:
        row_size (int): Length of the sequence to partition
        vocab_size (int): Maximum number of partitions (partition IDs 0 to vocab_size-1)

    Returns:
        numpy.ndarray: Array of shape (n_partitions, row_size) where each row
                      represents a unique partition assignment

    Example:
        >>> partitions = generate_partitions(3, 3)
        >>> print(partitions)
        [[0 0 0]
         [0 0 1]
         [0 1 1]
         [0 1 2]]
    """
    if row_size <= 0 or vocab_size <= 0:
        return np.array([]).reshape(0, row_size)

    # Generate all possible assignments of partition IDs to positions
    all_assignments = list(product(range(vocab_size), repeat=row_size))

    valid_partitions = []

    for assignment in all_assignments:
        # Check if this assignment uses consecutive partition IDs starting from 0
        if is_valid_partition(assignment):
            valid_partitions.append(assignment)

    return np.array(valid_partitions)

def is_valid_partition(assignment):
    """
    Check if a partition assignment follows the canonical/restricted growth string pattern.

    Rules:
    1. First element must be 0
    2. Each new partition ID k can only appear if all IDs 0,1,...,k-1 have already appeared

    Args:
        assignment (tuple): Tuple of partition IDs assigned to each position

    Returns:
        bool: True if the assignment is valid
    """
    if not assignment or assignment[0] != 0:
        return False

    seen_ids = {0}  # We've seen partition 0
    next_new_id = 1  # Next new partition ID that can be introduced

    for partition_id in assignment[1:]:  # Skip first element (already checked)
        if partition_id in seen_ids:
            # Using an already seen partition ID is always valid
            continue
        elif partition_id == next_new_id:
            # Introducing the next new partition ID in sequence
            seen_ids.add(partition_id)
            next_new_id += 1
        else:
            # Invalid: trying to use partition ID that's too high
            return False

    return True

